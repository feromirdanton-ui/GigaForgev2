"""Long-running mode: work through a queue of goals, resumably.

An agent harness that can only do one task per invocation is a tool; one that
keeps working through a list is an assistant.  This module is the loop:

* goals come from a plain text file (one per line, ``#`` comments) — no database,
  so a queue can be edited in any editor, generated by a script, or produced by
  another tool;
* every attempt is journalled to ``<queue>.state.json`` (goal hash → status,
  attempts, last error, run id), so a restart resumes instead of re-running what
  already succeeded, and a goal that keeps failing stops after ``max_attempts``;
* the loop keeps watching the file when it is empty (``idle_poll`` seconds), so it
  can be left running while goals are appended by something else;
* ``Ctrl-C`` stops between goals and leaves the journal consistent.

The chat engine is the driver, so a queued goal and a typed goal take exactly the
same path through the DAG.
"""
from __future__ import annotations

import hashlib
import json
import logging
import time
from pathlib import Path
from typing import Any, Callable, Iterable, Optional

__all__ = ["run_queue", "QueueState", "read_goals"]

log = logging.getLogger("gigaforge.loop")


class QueueState:
    """Persistent journal for one queue file.

    Kept beside the queue (``goals.txt`` → ``goals.txt.state.json``) so a queue
    can be moved or copied together with its progress.
    """

    def __init__(self, path: Path) -> None:
        self.path = path
        self.records: dict[str, dict[str, Any]] = {}
        self._load()

    def _load(self) -> None:
        try:
            payload = json.loads(self.path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return
        if isinstance(payload, dict):
            self.records = {str(k): dict(v) for k, v in payload.items() if isinstance(v, dict)}

    def save(self) -> None:
        try:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            tmp = self.path.with_suffix(self.path.suffix + ".tmp")
            tmp.write_text(json.dumps(self.records, indent=2, ensure_ascii=False), encoding="utf-8")
            tmp.replace(self.path)
        except OSError:  # pragma: no cover - a read-only checkout still runs
            log.debug("could not persist queue state", exc_info=True)

    # -- accessors ---------------------------------------------------------
    def get(self, goal: str) -> dict[str, Any]:
        return self.records.setdefault(_key(goal), {"goal": goal, "status": "pending", "attempts": 0})

    def is_finished(self, goal: str, *, max_attempts: int) -> bool:
        record = self.get(goal)
        status = str(record.get("status") or "pending")
        if status in {"done", "skipped"}:
            return True
        if status == "failed" and int(record.get("attempts") or 0) >= max_attempts:
            return True
        return False

    def finish(self, goal: str, *, status: str, run_id: str = "", error: str = "",
               accepted: bool = False) -> None:
        record = self.get(goal)
        record.update({
            "status": status,
            "attempts": int(record.get("attempts") or 0) + 1,
            "run_id": run_id or record.get("run_id", ""),
            "accepted": bool(accepted),
            "error": error[:500],
            "updated_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        })
        self.save()


def _key(goal: str) -> str:
    return hashlib.sha256(" ".join(goal.split()).lower().encode("utf-8")).hexdigest()[:16]


def read_goals(path: Path) -> list[str]:
    """Goals from *path*: one per line, ``#`` comments and blanks ignored."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return []
    goals: list[str] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        goals.append(line)
    return goals


def run_queue(
    engine: Any,
    *,
    repo: Optional[Path] = None,
    queue_path: Optional[Path] = None,
    max_attempts: int = 2,
    idle_poll: float = 5.0,
    once: bool = False,
    max_goals: int = 0,
    as_json: bool = False,
    emit: Callable[..., None] = print,
    should_stop: Optional[Callable[[], bool]] = None,
) -> int:
    """Drive *engine* over a goal queue.  Returns an exit code.

    ``once=True`` drains the queue and exits (a batch run); the default keeps
    watching the file, which is the long-running mode.  ``max_goals`` bounds a
    single invocation.
    """
    path = Path(queue_path) if queue_path else Path(".gigaforge") / "queue.txt"
    if not path.is_file():
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(
                "# GigaForge goal queue — one goal per line, '#' starts a comment.\n"
                "# `gigaforge chat --loop` works through this file and resumes where it stopped.\n",
                encoding="utf-8",
            )
        except OSError:
            emit(f"cannot create the queue file at {path}")
            return 2
        emit(f"created an empty queue at {path}; add goals and re-run")
        if once:
            return 0

    state = QueueState(path.with_suffix(path.suffix + ".state.json"))
    handled = 0
    failures = 0
    emit(f"queue: {path} ({len(read_goals(path))} goal(s), journal {state.path.name})")

    while True:
        goals = read_goals(path)
        pending = [g for g in goals if not state.is_finished(g, max_attempts=max_attempts)]
        if not pending:
            if once:
                break
            if should_stop is not None and should_stop():
                break
            time.sleep(max(0.5, idle_poll))
            continue

        goal = pending[0]
        record = state.get(goal)
        attempt = int(record.get("attempts") or 0) + 1
        emit(f"▶ [{attempt}/{max_attempts}] {goal}")
        started = time.monotonic()
        run_id = ""
        accepted = False
        error = ""

        try:
            for event in engine.stream(goal):
                kind = str(getattr(event, "kind", "") or "")
                data = getattr(event, "data", {}) or {}
                text = str(getattr(event, "text", "") or "")
                if kind == "step":
                    status = str(data.get("status") or "")
                    if status and status not in {"running"}:
                        emit(f"   · {data.get('node', '?')}: {status}")
                elif kind == "error":
                    error = text or error
                    emit(f"   ! {text[:200]}")
                elif kind == "tool" and text:
                    run_id = str(data.get("run_id") or run_id)
                if as_json:
                    emit(json.dumps(event.to_dict() if hasattr(event, "to_dict") else {},
                                    ensure_ascii=False, default=str))
            last = getattr(getattr(engine, "backend", None), "last_result", {}) or {}
            if isinstance(last, dict):
                run_id = str(last.get("run_id") or run_id)
                accepted = bool(last.get("accepted"))
                error = error or str(last.get("error") or "")
                if run_id and not accepted:
                    error = error or "the run finished without an accepted diff"
        except KeyboardInterrupt:  # pragma: no cover - interactive
            emit("interrupted; progress is journalled, re-run to resume")
            state.save()
            return 130
        except Exception as exc:  # noqa: BLE001 - a queue must survive one bad goal
            error = f"{type(exc).__name__}: {exc}"
            emit(f"   ! {error[:200]}")

        elapsed = time.monotonic() - started
        if accepted:
            state.finish(goal, status="done", run_id=run_id, accepted=True)
            emit(f"✓ done in {elapsed:.1f}s · run {run_id or '—'}")
        elif attempt >= max_attempts:
            state.finish(goal, status="failed", run_id=run_id, error=error)
            failures += 1
            emit(f"✗ failed after {attempt} attempt(s): {error[:160]}")
        else:
            state.finish(goal, status="pending", run_id=run_id, error=error)
            emit(f"… not accepted, will retry: {error[:160]}")
            time.sleep(min(30.0, 2.0 ** attempt))

        handled += 1
        if max_goals and handled >= max_goals:
            emit(f"stopping after {handled} goal(s) (--max-goals)")
            break
        if should_stop is not None and should_stop():
            break

    emit(f"queue finished: {handled} handled, {failures} failed")
    return 0 if failures == 0 else 1
